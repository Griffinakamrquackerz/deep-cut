// The velvet rope — an invite-only waitlist that throttles signups to a
// trickle (Resend free tier sends ~100 emails/day; the trickle stays well
// under it). Zero-migration by design: rows live in the events table with a
// null user_id (`name: "waitlist"`), latest status per email wins — the same
// append-only pattern as blocks and profile styles.
//
// Approval generates a Supabase Auth sign-in link and mails it through Resend
// (see approveEmail) — Supabase's own mailer is never in the path.
// NOTE: the rope only holds if "Allow new users to sign up" is switched OFF
// in Supabase Auth settings — invites still work with signups disabled.

import { supabaseAdmin } from "./supabase/admin";
import { siteUrl } from "./site";
import { sendEmail, inviteHtml } from "./email";

const EVENT = "waitlist";

export interface WaitlistEntry {
  email: string;
  status: "pending" | "approved";
  joinedAt: string; // first time we saw this email
}

export interface WaitlistState {
  pending: WaitlistEntry[]; // oldest first — the line, in order
  approved: WaitlistEntry[]; // newest first — recent invites on top
  approvedToday: number;
}

/** Replay the append-only log: latest status per email wins. */
export async function getWaitlist(): Promise<WaitlistState> {
  const { data } = await supabaseAdmin()
    .from("events")
    .select("props, created_at")
    .eq("name", EVENT)
    .order("created_at", { ascending: true })
    .limit(5000);

  const byEmail = new Map<string, WaitlistEntry & { approvedAt?: string }>();
  for (const row of data ?? []) {
    const p = row.props as { email?: string; status?: string };
    const email = p.email?.toLowerCase().trim();
    if (!email) continue;
    const prev = byEmail.get(email);
    const status = p.status === "approved" ? "approved" : "pending";
    byEmail.set(email, {
      email,
      status,
      joinedAt: prev?.joinedAt ?? (row.created_at as string),
      approvedAt: status === "approved" ? (row.created_at as string) : prev?.approvedAt,
    });
  }

  const all = [...byEmail.values()];
  const dayAgo = Date.now() - 24 * 60 * 60 * 1000;
  return {
    pending: all
      .filter((e) => e.status === "pending")
      .sort((a, b) => a.joinedAt.localeCompare(b.joinedAt)),
    approved: all
      .filter((e) => e.status === "approved")
      .sort((a, b) => (b.approvedAt ?? "").localeCompare(a.approvedAt ?? "")),
    approvedToday: all.filter(
      (e) => e.status === "approved" && e.approvedAt && new Date(e.approvedAt).getTime() > dayAgo,
    ).length,
  };
}

/**
 * Join the line. Idempotent: an email already in line keeps its spot (and an
 * approved one is told so). Returns the 1-based position in line.
 */
export async function joinWaitlist(
  rawEmail: string,
): Promise<{ status: "pending" | "approved"; position: number; isNew: boolean }> {
  const email = rawEmail.toLowerCase().trim();
  const state = await getWaitlist();

  const existingIdx = state.pending.findIndex((e) => e.email === email);
  if (existingIdx >= 0) return { status: "pending", position: existingIdx + 1, isNew: false };
  if (state.approved.some((e) => e.email === email))
    return { status: "approved", position: 0, isNew: false };

  await supabaseAdmin()
    .from("events")
    .insert({ user_id: null, name: EVENT, props: { email, status: "pending" } });
  return { status: "pending", position: state.pending.length + 1, isNew: true };
}

/**
 * The address that actually appears in an invite email.
 *
 * Built from generateLink's `hashed_token` rather than its `action_link`. The
 * action_link points at supabase.co and returns the session in a URL fragment,
 * which the server can never read — every invited person landed back on /login.
 * /auth/confirm verifies the hash server-side instead, so the link works, and
 * it's on thedeepcut.xyz where a stranger expects it to be.
 */
function confirmUrl(hashedToken: string, type: "invite" | "magiclink"): string {
  return `${siteUrl()}/auth/confirm?token_hash=${encodeURIComponent(hashedToken)}&type=${type}`;
}

/** Auth errors arrive with a literal `{}` message often enough that the message
 *  alone is useless. Keep the name and status, which are always populated. */
function describeAuthError(err: { name?: string; status?: number; message?: string } | null): string {
  if (!err) return "unknown_auth_error";
  const msg = (err.message ?? "").trim();
  return `${err.name ?? "AuthError"} ${err.status ?? "?"}: ${msg && msg !== "{}" ? msg : "no message"}`;
}

/**
 * Approve one email: generate a sign-in link, mail it ourselves, and log the
 * status flip. An email that already has an account still gets marked approved
 * so it leaves the line.
 *
 * The link is generated by Supabase but sent by Resend, deliberately. Letting
 * Supabase mail it (inviteUserByEmail) put the one email that actually admits a
 * person onto the built-in mailer, which caps at a handful of messages an hour
 * and reports its own failure as a literal `{}` — so invites stopped sending
 * partway through a batch with nothing to explain it. Resend is the same pipe
 * the confirmation and owner-alert mail already use, on the same verified
 * domain, and this app can see whether the send actually succeeded.
 */
/**
 * Seat somebody: mint their sign-in link and mail it.
 *
 * Returns the user id it seated, because generateLink is the only place that
 * id is on offer — the caller would otherwise have to go looking for a row
 * that has only just been created by a trigger.
 */
export async function approveEmail(
  email: string,
): Promise<{ ok: boolean; note?: string; userId?: string }> {
  const db = supabaseAdmin();
  const normalized = email.toLowerCase().trim();
  const options = { redirectTo: `${siteUrl()}/auth/callback` };

  let link: string | null = null;
  let note: string | undefined;
  let userId: string | undefined;

  const invite = await db.auth.admin.generateLink({ type: "invite", email: normalized, options });
  if (invite.data?.properties?.hashed_token) {
    link = confirmUrl(invite.data.properties.hashed_token, "invite");
    userId = invite.data.user?.id;
  } else if (invite.error && /already|exists|registered/i.test(invite.error.message)) {
    // They found their own way in already. `invite` refuses outright for an
    // existing user, but a magic link seats them just the same.
    const magic = await db.auth.admin.generateLink({
      type: "magiclink",
      email: normalized,
      options,
    });
    const hash = magic.data?.properties?.hashed_token;
    link = hash ? confirmUrl(hash, "magiclink") : null;
    userId = magic.data?.user?.id;
    note = link ? "already_registered" : describeAuthError(magic.error);
  } else {
    note = describeAuthError(invite.error);
  }

  if (!link) return { ok: false, note: note ?? "no_link_generated" };

  const sent = await sendEmail({
    to: normalized,
    subject: "🎟 Your Deep Cut ticket is ready",
    html: inviteHtml(link),
  });
  if (!sent.ok) {
    // The account exists now but nobody was told. Deliberately left in the line
    // so the next attempt retries the send instead of stranding them as
    // "approved" with no way in. Resend's own words ride along — "the ticket
    // email didn't go out" is not a diagnosis.
    return { ok: false, note: `email_failed — ${sent.error ?? "no reason given"}` };
  }

  await db
    .from("events")
    .insert({ user_id: null, name: EVENT, props: { email: normalized, status: "approved" } });
  return { ok: true, note, userId };
}

/** The daily trickle: approve the next N in line, oldest first. */
export async function approveNext(
  n: number,
): Promise<{ approved: string[]; failed: Array<{ email: string; note?: string }> }> {
  const { pending } = await getWaitlist();
  const batch = pending.slice(0, Math.max(0, n));
  const approved: string[] = [];
  const failed: Array<{ email: string; note?: string }> = [];
  for (const entry of batch) {
    const res = await approveEmail(entry.email);
    if (res.ok) approved.push(entry.email);
    else failed.push({ email: entry.email, note: res.note });
  }
  return { approved, failed };
}
